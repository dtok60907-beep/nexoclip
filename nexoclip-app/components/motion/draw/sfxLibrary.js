const COUNT = new Map(SFX_LIBRARY);
// Names the drawing contract or a model may use that the library files under another name.
const ALIASES = { whoosh_short: 'transition', boom_start: 'scene-boom', 'word': 'word-tick', rain: 'rain-roof', ambience: 'wind', bell: 'ding', chime: 'ding', explosion: 'boom', crash: 'impact', swoosh: 'swish', typing: 'type', camera: 'shutter', money: 'kaching', win: 'tada', fail: 'buzzer', wrong: 'buzzer', right: 'correct', engine: 'engine-start', car: 'car-speed', motorbike: 'motorbike-pass', elevator: 'lift-ding', door: 'door-open', crowd: 'applause' };

export const SFX_NAMES = SFX_LIBRARY.map(([name]) => name);

// The file for the k-th use of a cue name (k rotates the variations), or null when nothing fits.
export function sfxPath(name, k = 0) {
  const key = String(name || '').trim().toLowerCase().replace(/[\s_]+/g, '-');
  const found = COUNT.has(key) ? key : COUNT.has(ALIASES[key]) ? ALIASES[key] : null;
  if (!found) return null;
  return `motion-sfx/lib/${found}-${(Math.abs(k) % COUNT.get(found)) + 1}.mp3`;
}
